sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', fmt='.3f')
plt.title('Корреляционная матрица')
plt.show()

"""### Обоснование спецификаций модели для каждой гипотезы:

Для проверки гипотез используется множественная линейная регрессия. Зависимая переменная addiction_score. В интерпретации анализируются полученные коэффицента в среднем при прочих равных.

Для проверки гипотезы H₁ (экранное время) в модель включена переменная daily_screen_time_hours. Ожидается положительный знак коэффициента и положительная связь. Чем больше времени человек проводит за экраном, тем выше риск зависимости (Радаев, 2025).

Для проверки гипотезы H₂ (социальные сети) в модель включена переменная social_media_hours. Ожидается положительный знак коэффициента. Социальные сети имеют алгоритмы, удерживающие внимание пользователя, что может усиливать зависимость (Максименко и др., 2021).

Для проверки гипотезы H₃ (сон) в модель включена переменная sleep_hours. Ожидается отрицательный знак коэффициента. Недосып ухудшает самоконтроль, что может усиливать использование смартфона (Cain & Gradisar, 2010).

Для проверки гипотезы H₄ (стресс) в модель включена переменная stress_encoded. Ожидается положительный знак коэффициента. Стресс может увеличивать пользование соцсетями как способ снятия напряжения (Радаев, 2024).
"""

model = smf.ols('addiction_score ~ daily_screen_time_hours + sleep_hours + stress_encoded + social_media_hours', data=df_clean).fit()
print(model.summary())

"""## Проверка условий Гаусса-Маркова

Мультиколлинеарность
"""

from statsmodels.stats.outliers_influence import variance_inflation_factor
X_vif = df_clean[['daily_screen_time_hours', 'social_media_hours', 'sleep_hours', 'stress_encoded']]
X_vif = sm.add_constant(X_vif)
vif_data = pd.DataFrame({
    'Переменная': X_vif.columns,
    'VIF': [variance_inflation_factor(X_vif.values, i) for i in range(X_vif.shape[1])]
})
print(vif_data)

"""Все значения VIF < 5, что свидетельствует об отсутствии мультиколлинеарности.

Гомоскедастичность (тест Бройша-Пагана)
"""

from statsmodels.stats.diagnostic import het_breuschpagan
bp_test = het_breuschpagan(model.resid, model.model.exog)
print(bp_test)

"""Тест Бройша-Пагана выявил наличие гетероскедастичности (p < 0.05). Для коррекции стандартных ошибок использованы оценки HC3, что позволяет делать корректные статистические выводы.

Автокорреляция (тест Дарбина-Уотсона)
"""

from statsmodels.stats.stattools import durbin_watson
residuals = model.resid
dw = durbin_watson(residuals)
print(dw)

"""Результат примерно 1.977. Значение близко к 2, автокорреляция отсутствует.

Линейность (тест Рамсея)
"""

from statsmodels.stats.diagnostic import linear_reset
reset_test = linear_reset(model, power=2, use_f=True)
print(reset_test)
residuals = model.resid

"""Линейность отсутсвует. Но данные переменные оказались статистически значимыми (p < 0.05), значит мы их оставляем для анализа.

Нормальность остатков (тест Шапиро-Уилка)
"""

from scipy.stats import shapiro
stat, p = shapiro(residuals)
print(p)

